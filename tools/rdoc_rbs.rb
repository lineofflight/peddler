# Teaches RDoc what it doesn't know of Peddler's comments. rakelib/docs.rake loads it before RDoc runs.
#
# RDoc shows a method's signature above its comment, from `#:` lines or from sig/. It doesn't know doc-style inline
# RBS, `# @rbs name: Type -- description`, whose lines would run together as 1 paragraph. They become a list of
# the parameters that have a description, where the lines stood, without the types the signature already shows.
# The sentences that say what a method raises would run together too. Several become a list under "Raises:".
require "rdoc"

module RDocRBS
  ANNOTATION = /\A@rbs (\S+?):? (.*)\z/
  # 2 or more sentences that start a line with "Raises", each with the lines it runs on to
  RAISES = /^Raises .*(?:\n(?!Raises |$).+)*(?:\nRaises .*(?:\n(?!Raises |$).+)*)+/
  # What opens a generated file. RDoc reads it as a description of `module Peddler`.
  NOTICE = /\A(This file is generated|Generated by peddler-codegen)\.[^\n]*\z/

  # The text of a comment as RDoc should read it
  def self.prose(text)
    return "" if text.strip.match?(NOTICE)

    kept = []
    items = []
    returns = current = nil
    flush = lambda do
      kept << "" << items.map { |name, description| "- `#{name}`: #{description}" }.join("\n") << "" unless items.empty?
      kept << "" << "Returns #{returns}" << "" if returns
      items = []
      returns = nil
    end
    text.each_line(chomp: true) do |line|
      if line.start_with?("@rbs ")
        current = nil
        name, rest = line.match(ANNOTATION)&.captures
        # An instance variable, `@rbs skip`, or a parameter with a type and nothing to say
        next if name.nil? || name.start_with?("@") || !rest.include?(" -- ")

        current = +rest.split(" -- ", 2).last
        name == "return" ? returns = current : items << [name, current]
      elsif current && line.start_with?("  ")
        current << " " << line.strip
      else
        current = nil
        flush.call
        kept << line
      end
    end
    flush.call
    # The line above the list keeps it apart from the list of parameters: Markdown makes 1 list of 2 that meet.
    kept.join("\n").gsub(RAISES) do |sentences|
      items = sentences.split(/\n(?=Raises )/).map { |sentence| "- #{sentence.delete_prefix("Raises ").tr("\n", " ")}" }
      "\nRaises:\n\n#{items.join("\n")}\n"
    end
  end

  # RDoc links a type in a signature by its full name, or by its last part when no other class has it. An
  # annotation names a class as Ruby finds it from inside Peddler, such as `Native::Engine`.
  module TypeNames
    def type_name_lookup
      @type_name_lookup ||= begin
        lookup = super
        inside = lookup.select { |name, _| name.start_with?("Peddler::") }
        inside.transform_keys { |name| name.delete_prefix("Peddler::") }.merge(lookup)
      end
    end
  end

  # What a formatter of HTML does with a block of raw HTML
  module InertHTML
    def accept_raw(raw)
      @res << "\n<p>#{CGI.escapeHTML(raw.parts.join("\n"))}</p>\n"
    end
  end

  # RDoc documents no way to add such names, nor to keep a block of HTML out of a page, so TypeNames and InertHTML
  # each go in front of a method of its own. Were a release to drop or rename one, the site would build, with every
  # one of those links gone or a block of HTML live again. The docs task calls this first.
  def self.verify!
    unless RDoc::Store.instance_method(:type_name_lookup).super_method
      raise "tools/rdoc_rbs.rb links the types of a signature through RDoc::Store#type_name_lookup, and RDoc " \
        "#{RDoc::VERSION} has no such method. Find what took its place, or the signatures lose their links."
    end
    return if RDoc::Markup::ToHtml.instance_method(:accept_raw).super_method

    raise "tools/rdoc_rbs.rb shows a block of raw HTML as text through RDoc::Markup::ToHtml#accept_raw, and RDoc " \
      "#{RDoc::VERSION} has no such method. Find what took its place, or a tag in a comment is live on the site."
  end
end

# Markdown hands a paragraph that starts with a tag to the page as it is, and most of the text is Amazon's. The
# page shows such a paragraph as the text it is, as RDoc shows a tag inside one: nothing a spec says is markup.
RDoc::Markup::ToHtml.prepend(RDocRBS::InertHTML)
RDoc::Markup::PreProcess.post_process do |comment, _code_object|
  comment.text = RDocRBS.prose(comment.text) if comment.is_a?(RDoc::Comment)
end
RDoc::Store.prepend(RDocRBS::TypeNames)
