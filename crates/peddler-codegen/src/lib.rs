use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

pub mod clients;
pub mod facades;
pub mod manifest;
pub mod models;
pub mod pagination;
pub mod supplemental;
pub use supplemental::generate_supplemental;

#[derive(Debug)]
pub struct GenerationError(pub String);

impl std::fmt::Display for GenerationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for GenerationError {}

impl From<std::io::Error> for GenerationError {
    fn from(error: std::io::Error) -> Self {
        Self(error.to_string())
    }
}

impl From<serde_json::Error> for GenerationError {
    fn from(error: serde_json::Error) -> Self {
        Self(error.to_string())
    }
}

/// Render all pinned API models without reading Git metadata or writing files.
/// `spec_dir` is the checkout's `models` directory; output paths are repository-relative.
pub fn generate_models(
    spec_dir: &Path,
    revision: &str,
) -> Result<BTreeMap<PathBuf, String>, GenerationError> {
    if revision.contains(['\n', '\r']) {
        return Err(GenerationError("revision must be a single line".into()));
    }
    let mut output = BTreeMap::new();
    let base = Path::new("crates/peddler/src/apis");
    let modules = manifest::ALL_APIS
        .iter()
        .map(|api| quote::format_ident!("{}", api.module));
    let root = quote::quote!(#(pub mod #modules;)*);
    output.insert(
        base.join("mod.rs"),
        format!("{}{}", notice("all API models"), format_tokens(root)?),
    );
    for api in manifest::ALL_APIS {
        let spec: serde_json::Value =
            serde_json::from_slice(&fs::read(spec_dir.join(api.source))?)?;
        let definitions = models::normalize_definitions(&spec)
            .map_err(|error| GenerationError(format!("{}: {error}", api.source)))?;
        let models = models::render(definitions)
            .map_err(|error| GenerationError(format!("{}: {error}", api.source)))?;
        let notice = notice(api.source);
        output.insert(
            base.join(api.module).join("mod.rs"),
            format!("{notice}pub mod models;\n"),
        );
        output.insert(
            base.join(api.module).join("models.rs"),
            format!("{notice}{models}"),
        );
    }
    Ok(output)
}

fn notice(source: &str) -> String {
    format!("// Generated by peddler-codegen. Do not edit.\n// Source: {source}\n\n")
}

fn format_tokens(tokens: impl quote::ToTokens) -> Result<String, GenerationError> {
    let file = syn::parse2(tokens.to_token_stream())
        .map_err(|error| GenerationError(error.to_string()))?;
    Ok(prettyplease::unparse(&file))
}

/// Render all pinned models, public facades, dispatch and Ruby.
pub fn generate(
    spec_dir: &Path,
    revision: &str,
) -> Result<BTreeMap<PathBuf, String>, GenerationError> {
    let mut output = generate_models(spec_dir, revision)?;
    let base = Path::new("crates/peddler/src/apis");
    output
        .get_mut(&base.join("mod.rs"))
        .unwrap()
        .push_str("\npub mod dispatch;\npub use dispatch::execute;\npub mod pagination;\n");
    let mut clients = Vec::new();
    let mut specs = BTreeMap::new();
    for api in manifest::ALL_APIS {
        let spec: serde_json::Value =
            serde_json::from_slice(&fs::read(spec_dir.join(api.source))?)?;
        clients.push((api, clients::render(&spec, api)?));
        specs.insert(api.module, spec);
    }
    let source = match spec_dir.parent().and_then(Path::parent) {
        Some(root) => pagination::load(root)?,
        None => pagination::Source::default(),
    };
    let resolved = pagination::resolve(&source, &clients, &specs)?;
    for (api, operations) in &clients {
        let prefix = notice(api.source);
        let mapped: Vec<_> = resolved.iter().filter(|r| r.module == api.module).collect();
        output.insert(
            base.join(api.module).join("facade.rs"),
            format!("{prefix}{}", facades::rust(operations, &mapped)?),
        );
        let module = quote::quote! {
            pub mod models;
            mod facade;
            pub use facade::*;
        };
        output.insert(
            base.join(api.module).join("mod.rs"),
            format!("{prefix}{}", format_tokens(module)?),
        );
    }
    output.insert(
        base.join("dispatch.rs"),
        format!(
            "{}{}",
            notice("all operations"),
            facades::dispatch(&clients, &resolved)?
        ),
    );
    output.insert(
        base.join("pagination.rs"),
        format!(
            "{}{}",
            notice("pagination.json"),
            facades::pagination_table(&resolved)?
        ),
    );
    let (ruby, rbs) = facades::ruby(&clients, &resolved);
    output.insert(PathBuf::from("lib/peddler/native/apis.rb"), ruby);
    output.insert(PathBuf::from("sig/peddler/native/apis.rbs"), rbs);
    output.insert(
        PathBuf::from("crates/peddler-codegen/operation-inventory.json"),
        facades::inventory(&clients, revision, &resolved, &source)?,
    );
    output.extend(generate_supplemental(
        spec_dir
            .parent()
            .ok_or_else(|| GenerationError("models directory requires a checkout parent".into()))?,
        revision,
    )?);
    Ok(output)
}
