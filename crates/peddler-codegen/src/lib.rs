#[derive(Debug)]
pub struct GenerationError(pub String);

impl std::fmt::Display for GenerationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for GenerationError {}

impl From<std::io::Error> for GenerationError {
    fn from(error: std::io::Error) -> Self {
        Self(error.to_string())
    }
}

impl From<serde_json::Error> for GenerationError {
    fn from(error: serde_json::Error) -> Self {
        Self(error.to_string())
    }
}

fn notice(source: &str) -> String {
    format!("// Generated by peddler-codegen. Do not edit.\n// Source: {source}\n\n")
}

/// Formats generated Rust source, with each doc in `///` lines.
pub(crate) fn format_source(source: &str) -> Result<String, GenerationError> {
    let tokens: proc_macro2::TokenStream = source
        .parse()
        .map_err(|error: proc_macro2::LexError| GenerationError(error.to_string()))?;
    let file: syn::File =
        syn::parse2(rustdoc::lines(tokens)?).map_err(|error| GenerationError(error.to_string()))?;
    Ok(prettyplease::unparse(&file))
}

/// A name as a segment of a JSON pointer.
pub(crate) fn escape_pointer(name: &str) -> String {
    name.replace('~', "~0").replace('/', "~1")
}

/// The name a segment of a JSON pointer stands for.
pub(crate) fn unescape_pointer(segment: &str) -> String {
    segment.replace("~1", "/").replace("~0", "~")
}

/// Every file under `dir` whose path relative to it `keep` keeps, in byte order, with `/`
/// between its parts. A missing `dir` has none, as for Ruby's `Dir.glob`.
pub(crate) fn files(
    dir: &Path,
    keep: impl Fn(&str) -> bool,
) -> Result<Vec<String>, GenerationError> {
    let mut found = Vec::new();
    if !dir.is_dir() {
        return Ok(found);
    }
    let mut pending = vec![String::new()];
    while let Some(relative) = pending.pop() {
        for entry in fs::read_dir(dir.join(&relative))? {
            let entry = entry?;
            let name = entry.file_name().into_string().map_err(|name| {
                GenerationError(format!("{}: a file name must be UTF-8", name.display()))
            })?;
            let path = if relative.is_empty() {
                name
            } else {
                format!("{relative}/{name}")
            };
            if entry.file_type()?.is_dir() {
                pending.push(path);
            } else if keep(&path) {
                found.push(path);
            }
        }
    }
    found.sort();
    Ok(found)
}

/// Render every model in the checkout, public facades, dispatch and Ruby, without reading
/// Git metadata or writing files. `spec_dir` is the checkout's `models` directory; output
/// paths are repository-relative. What it can't map, it warns of on stderr.
pub fn generate(
    spec_dir: &Path,
    revision: &str,
) -> Result<BTreeMap<PathBuf, String>, GenerationError> {
    if revision.contains(['\n', '\r']) {
        return Err(GenerationError("revision must be a single line".into()));
    }
    let base = Path::new("crates/peddler/src/apis");
    let mut output = BTreeMap::new();
    let mut clients = Vec::new();
    let mut specs = BTreeMap::new();
    let mut parsed = Vec::new();
    for source in manifest::sources(spec_dir)? {
        // What is refused of a spec names its file: a file that is not JSON, a name, a
        // model or an operation.
        let spec: serde_json::Value = fs::read(spec_dir.join(&source))
            .map_err(GenerationError::from)
            .and_then(|bytes| Ok(serde_json::from_slice(&bytes)?))
            .map_err(|error| GenerationError(format!("{source}: {error}")))?;
        parsed.push((source, spec));
    }
    let apis = manifest::derive(&parsed)?;
    for (api, (_, spec)) in apis.iter().zip(parsed) {
        let located = |error: GenerationError| GenerationError(format!("{}: {error}", api.source));
        let models = models::normalize_definitions(&spec)
            .and_then(models::render)
            .map_err(located)?;
        output.insert(
            base.join(&api.module).join("models.rs"),
            format!("{}{models}", notice(&api.source)),
        );
        clients.push((api, clients::render(&spec, api).map_err(located)?));
        specs.insert(api.module.as_str(), spec);
    }
    let modules: String = apis
        .iter()
        .map(|api| {
            let doc = facades::module_doc(api, &specs[api.module.as_str()]["info"]);
            format!("{doc}pub mod {};\n", api.module)
        })
        .collect();
    output.insert(
        base.join("mod.rs"),
        format!(
            "{}{}\n/// Sends an operation by its key.\npub mod dispatch;\npub use dispatch::execute;\n/// The pagination mapping of each operation that returns pages.\npub mod pagination;\n",
            notice("all API models"),
            format_source(&modules)?
        ),
    );
    let source = match spec_dir.parent().and_then(Path::parent) {
        Some(root) => pagination::load(root)?,
        None => pagination::Source::default(),
    };
    let pagination::Resolution {
        resolved,
        unmapped,
        stale,
    } = pagination::resolve(&source, &clients, &specs)?;
    for key in &stale {
        eprintln!(
            "peddler-codegen: warning: {}: {key} is of no API left; remove it",
            pagination::SOURCE
        );
    }
    for op in &unmapped {
        eprintln!(
            "peddler-codegen: warning: {}: {}: {} looks like a page token, and {} neither maps nor excludes {}: no *_pages method",
            op.source,
            op.id,
            op.field,
            pagination::SOURCE,
            op.key
        );
    }
    for (api, operations) in &clients {
        let prefix = notice(&api.source);
        let mapped: Vec<_> = resolved.iter().filter(|r| r.module == api.module).collect();
        output.insert(
            base.join(&api.module).join("facade.rs"),
            format!(
                "{prefix}{}",
                facades::rust(operations, &mapped)
                    .map_err(|error| GenerationError(format!("{}: {error}", api.source)))?
            ),
        );
        output.insert(
            base.join(&api.module).join("mod.rs"),
            format!("{prefix}/// The models of this API's requests and responses.\npub mod models;\nmod facade;\npub use facade::*;\n"),
        );
    }
    output.insert(
        base.join("dispatch.rs"),
        format!(
            "{}{}",
            notice("all operations"),
            facades::dispatch(&clients, &resolved)?
        ),
    );
    output.insert(
        base.join("pagination.rs"),
        format!(
            "{}{}",
            notice("pagination.json"),
            facades::pagination_table(&resolved)?
        ),
    );
    output.insert(
        PathBuf::from("lib/peddler/native/apis.rb"),
        facades::ruby(&clients, &resolved, &specs)?,
    );
    output.insert(
        PathBuf::from("crates/peddler-codegen/operation-inventory.json"),
        facades::inventory(&clients, revision, &resolved, &source, &unmapped)?,
    );
    output.extend(generate_supplemental(
        spec_dir
            .parent()
            .ok_or_else(|| GenerationError("models directory requires a checkout parent".into()))?,
        revision,
    )?);
    Ok(output)
}
