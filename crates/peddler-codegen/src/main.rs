use peddler_codegen::{GenerationError, generate};
use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
};

fn main() {
    if let Err(error) = run() {
        eprintln!("peddler-codegen: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), GenerationError> {
    let mut root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let mut output_root = None;
    let mut check = false;
    let mut args = std::env::args_os().skip(1);
    while let Some(arg) = args.next() {
        if arg == "--root" || arg == "--output-root" {
            let path = args
                .next()
                .filter(|value| !value.to_string_lossy().starts_with("--"))
                .ok_or_else(|| {
                    GenerationError(format!("{} requires a path", arg.to_string_lossy()))
                })?;
            if arg == "--root" {
                root = path.into();
            } else {
                output_root = Some(PathBuf::from(path));
            }
        } else if arg == "--check" {
            check = true;
        } else {
            return Err(GenerationError(format!(
                "unknown argument: {}",
                arg.to_string_lossy()
            )));
        }
    }
    let revision = fs::read_to_string(root.join("selling-partner-api-models.sha"))?;
    let revision = revision.trim();
    if revision.len() != 40 || !revision.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err(GenerationError(
            "pin must contain a full Git revision".into(),
        ));
    }
    let checkout = root.join("selling-partner-api-models");
    peddler_codegen::checkout::verify(&checkout, revision)?;
    let output = generate(&checkout.join("models"), revision)?;
    let dest = output_root.unwrap_or(root);
    // A generated file no longer generated is of a model or a schema Amazon removed.
    let mut obsolete = Vec::new();
    for base in GENERATED_RUST {
        for path in generated_rust_files(&dest, Path::new(base))? {
            if !output.contains_key(&path) {
                obsolete.push(path);
            }
        }
    }
    if check {
        let mut drifted: Vec<_> = output
            .iter()
            .filter(|(path, content)| {
                fs::read(dest.join(path)).ok().as_deref() != Some(content.as_bytes())
            })
            .map(|(path, _)| path.display().to_string())
            .collect();
        drifted.extend(obsolete.iter().map(|path| path.display().to_string()));
        if !drifted.is_empty() {
            return Err(GenerationError(format!(
                "generated outputs missing or drifted:\n{}",
                drifted.join("\n")
            )));
        }
    } else {
        // Stage every changed file before replacing any destination. Schema errors cannot
        // leave partially generated output; each replacement is an atomic rename.
        let mut staged = Vec::new();
        for (path, content) in output {
            let path = dest.join(path);
            if fs::read(&path).ok().as_deref() == Some(content.as_bytes()) {
                continue;
            }
            let parent = path.parent().expect("generated paths have parents");
            fs::create_dir_all(parent)?;
            let mut file = tempfile::NamedTempFile::new_in(parent)?;
            file.write_all(content.as_bytes())?;
            staged.push((path, file));
        }
        for (path, file) in staged {
            file.persist(path)
                .map_err(|error| GenerationError(error.to_string()))?;
        }
        for path in obsolete {
            let path = dest.join(path);
            fs::remove_file(&path)?;
            // The directory of a removed API goes with its last file.
            if let Some(parent) = path.parent()
                && fs::read_dir(parent)?.next().is_none()
            {
                fs::remove_dir(parent)?;
            }
        }
    }
    Ok(())
}

/// The directories of generated Rust, where a file that starts with the generated notice
/// and is no longer generated is obsolete
const GENERATED_RUST: [&str; 5] = [
    "crates/peddler/src/apis",
    "crates/peddler/src/reports",
    "crates/peddler/src/feeds",
    "crates/peddler/src/notifications",
    "crates/peddler/src/data_kiosk",
];

fn generated_rust_files(root: &Path, relative: &Path) -> Result<Vec<PathBuf>, GenerationError> {
    let mut files = Vec::new();
    let Ok(entries) = fs::read_dir(root.join(relative)) else {
        return Ok(files);
    };
    for entry in entries {
        let entry = entry?;
        let path = relative.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            files.extend(generated_rust_files(root, &path)?);
        } else if path.extension().is_some_and(|ext| ext == "rs")
            && fs::read_to_string(root.join(&path))?.starts_with("// Generated by peddler-codegen.")
        {
            files.push(path);
        }
    }
    Ok(files)
}
